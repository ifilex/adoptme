export const getTranslation = (lang?: SupportedLanguage | string, key?: string, fallback?: string): string => {
  if (!key) return '';
  const safeLang = (lang && translations[lang as SupportedLanguage]) ? (lang as SupportedLanguage) : 'en';
  const langDict = translations[safeLang] || translations.en;
  return langDict[key] || translations.en[key] || fallback || key;
};
